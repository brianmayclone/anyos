//! Cargo.lock reading and writing.
//!
//! Supports Cargo.lock v3 format for reproducible builds.

use crate::fs;
use crate::prelude::*;
use crate::toml;
use anyos_std::println;

/// A pinned package from Cargo.lock.
#[derive(Debug, Clone)]
pub struct LockedPackage {
    pub name: String,
    pub version: String,
    /// Source URI. None = path dependency or root package.
    /// "registry+https://github.com/rust-lang/crates.io-index" = crates.io
    pub source: Option<String>,
    pub checksum: Option<String>,
    pub dependencies: Vec<String>,
}

/// Parsed Cargo.lock contents.
#[derive(Debug, Clone)]
pub struct Lockfile {
    pub version: u32,
    pub packages: Vec<LockedPackage>,
}

impl Lockfile {
    pub fn new() -> Self {
        Self {
            version: 3,
            packages: Vec::new(),
        }
    }

    /// Find a locked version for a crate name.
    pub fn find(&self, name: &str) -> Option<&LockedPackage> {
        self.packages.iter().find(|p| p.name == name)
    }

    /// Add or update a package entry.
    pub fn upsert(&mut self, pkg: LockedPackage) {
        if let Some(existing) = self.packages.iter_mut().find(|p| p.name == pkg.name) {
            *existing = pkg;
        } else {
            self.packages.push(pkg);
        }
    }
}

/// Read a Cargo.lock file. Returns None if it doesn't exist.
pub fn read(dir: &str) -> Option<Lockfile> {
    let path = format!("{}/Cargo.lock", dir);
    let content = fs::read_file(&path)?;

    let table = toml::parse(&content);
    let version = table.get("version").and_then(|v| v.as_i64()).unwrap_or(3) as u32;

    let mut packages = Vec::new();

    if let Some(toml::Value::Array(pkg_array)) = table.get("package") {
        for pkg_val in pkg_array {
            if let toml::Value::Table(pkg) = pkg_val {
                let name = pkg
                    .get("name")
                    .and_then(|v| v.as_str())
                    .unwrap_or("")
                    .to_string();
                let version_str = pkg
                    .get("version")
                    .and_then(|v| v.as_str())
                    .unwrap_or("0.0.0")
                    .to_string();
                let source = pkg
                    .get("source")
                    .and_then(|v| v.as_str())
                    .map(|s| s.to_string());
                let checksum = pkg
                    .get("checksum")
                    .and_then(|v| v.as_str())
                    .map(|s| s.to_string());

                let mut dependencies = Vec::new();
                if let Some(toml::Value::Array(deps)) = pkg.get("dependencies") {
                    for dep in deps {
                        if let toml::Value::String(s) = dep {
                            dependencies.push(s.clone());
                        }
                    }
                }

                if !name.is_empty() {
                    packages.push(LockedPackage {
                        name,
                        version: version_str,
                        source,
                        checksum,
                        dependencies,
                    });
                }
            }
        }
    }

    Some(Lockfile { version, packages })
}

/// Write a Cargo.lock file.
pub fn write(dir: &str, lockfile: &Lockfile) {
    let mut out = String::new();
    out.push_str("# This file is automatically @generated by ccargo.\n");
    out.push_str("# It is not intended for manual editing.\n");
    out.push_str(&format!("version = {}\n", lockfile.version));

    // Sort packages for deterministic output
    let mut sorted: Vec<&LockedPackage> = lockfile.packages.iter().collect();
    sorted.sort_by(|a, b| a.name.cmp(&b.name).then(a.version.cmp(&b.version)));

    for pkg in &sorted {
        out.push('\n');
        out.push_str("[[package]]\n");
        out.push_str(&format!("name = \"{}\"\n", pkg.name));
        out.push_str(&format!("version = \"{}\"\n", pkg.version));
        if let Some(ref source) = pkg.source {
            out.push_str(&format!("source = \"{}\"\n", source));
        }
        if let Some(ref checksum) = pkg.checksum {
            out.push_str(&format!("checksum = \"{}\"\n", checksum));
        }
        if !pkg.dependencies.is_empty() {
            out.push_str("dependencies = [\n");
            for dep in &pkg.dependencies {
                out.push_str(&format!(" \"{}\",\n", dep));
            }
            out.push_str("]\n");
        }
    }

    let path = format!("{}/Cargo.lock", dir);
    fs::write_file(&path, out.as_bytes());
}
