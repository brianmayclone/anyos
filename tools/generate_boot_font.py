"""
Generate an 8x16 bitmap font binary for the bootloader's font renderer.

Output format:
  95 glyphs (ASCII 32-126), 16 bytes per glyph, total 1520 bytes.
  Each byte = one row of 8 pixels, MSB = leftmost pixel.
  Glyph order: ASCII 32 first, ASCII 126 last.

Usage: python3 tools/generate_boot_font.py <output.bin> [input.psf]
"""

import gzip
import os
import struct
import sys

PSF2_MAGIC = 0x864AB572
FIRST_GLYPH = 32
LAST_GLYPH = 126
NUM_GLYPHS = LAST_GLYPH - FIRST_GLYPH + 1  # 95
GLYPH_HEIGHT = 16
GLYPH_WIDTH = 8
OUTPUT_SIZE = NUM_GLYPHS * GLYPH_HEIGHT  # 1520

SYSTEM_FONT_PATHS = [
    "/usr/share/consolefonts/default8x16.psfu.gz",
    "/usr/share/kbd/consolefonts/default8x16.psfu.gz",
    "/usr/lib/kbd/consolefonts/default8x16.psfu.gz",
    "/usr/share/consolefonts/Lat15-Fixed16.psf.gz",
]


def parse_psf2(data):
    """Parse a PSF2 font file and return 95 glyphs (ASCII 32-126) as bytes."""
    if len(data) < 32:
        raise ValueError("File too small for PSF2 header")

    magic, version, headersize, flags, numglyph, bytesperglyph, height, width = \
        struct.unpack_from("<IIIIIIII", data, 0)

    if magic != PSF2_MAGIC:
        raise ValueError(f"Not a PSF2 file (magic=0x{magic:08X})")

    print(f"PSF2: version={version}, {width}x{height}, {numglyph} glyphs, "
          f"{bytesperglyph} bytes/glyph", file=sys.stderr)

    glyph_data = data[headersize:]
    result = bytearray()

    for ch in range(FIRST_GLYPH, LAST_GLYPH + 1):
        if ch >= numglyph:
            result.extend(b'\x00' * GLYPH_HEIGHT)
            continue

        offset = ch * bytesperglyph
        glyph = glyph_data[offset:offset + bytesperglyph]

        if width == 8 and height == 16:
            result.extend(glyph[:GLYPH_HEIGHT])
        else:
            # Resample: take rows proportionally, pad/truncate width to 8
            row_bytes = (width + 7) // 8
            for row in range(GLYPH_HEIGHT):
                src_row = row * height // GLYPH_HEIGHT
                if src_row < height and row_bytes > 0:
                    b = glyph[src_row * row_bytes]
                    if width < 8:
                        b <<= (8 - width)
                    result.append(b & 0xFF)
                else:
                    result.append(0)

    return bytes(result)


def load_font_file(path):
    """Load a font file, decompressing .gz if needed. Returns raw bytes."""
    if path.endswith(".gz"):
        with gzip.open(path, "rb") as f:
            return f.read()
    else:
        with open(path, "rb") as f:
            return f.read()


